function generatedMain(): string {
  return `import { StrictMode } from 'react';\nimport { createRoot } from 'react-dom/client';\nimport App from './App';\nimport './styles.css';\n\ncreateRoot(document.getElementById('root')!).render(<StrictMode><App /></StrictMode>);\n`;
}

function generatedViteConfig(pages: NilaPage[]): string {
  const inputs = pages.map((page, index) => `${JSON.stringify(`page${index}`)}: resolve(__dirname, ${JSON.stringify(page.isHome ? 'index.html' : `${page.slug}/index.html`)})`).join(',\n      ');
  return `import { defineConfig } from 'vite';\nimport react from '@vitejs/plugin-react';\nimport { resolve } from 'node:path';\n\nexport default defineConfig({ plugins:[react()], build:{ rollupOptions:{ input:{\n      ${inputs}\n    } } } });\n`;
}

function htmlForPage(input: ExportProjectInput, page: NilaPage): string {
  const head = generateHeadMarkup(input.seo, page, input.assets);
  return `<!doctype html>\n<html lang="${escapeHtml(input.seo.language || 'en')}" data-generator="nila">\n<head>\n<meta charset="UTF-8" />\n<meta name="viewport" content="width=device-width, initial-scale=1.0" />\n<meta name="generator" content="${GENERATED_BY}" />\n<!-- Generated by ${GENERATED_BY}. https://github.com/nadeemmhdm/nila-drag-and-drop-website-builder -->\n${head}</head>\n<body data-page-id="${escapeHtml(page.id)}">\n<div id="root"></div>\n<script type="module" src="/src/main.tsx"></script>\n</body>\n</html>\n`;
}

export function generateProjectFiles(input: ExportProjectInput): ExportFile[] {
  const pkg = safePackageName(input.projectName);
  const files: ExportFile[] = [];
  files.push({ path:'package.json', content: JSON.stringify({ name:pkg, private:true, version:'1.0.0', type:'module', scripts:{dev:'vite',build:'tsc -b && vite build',preview:'vite preview'}, dependencies:{'lucide-react':'^0.468.0',react:'^19.3.1','react-dom':'^19.3.1'}, devDependencies:{'@types/react':'^19.0.0','@types/react-dom':'^19.0.0','@vitejs/plugin-react':'^6.1.2',typescript:'^7.0.2',vite:'^8.3.4'}, nilaGenerated:true }, null, 2)+'\n' });
  files.push({ path:'tsconfig.json', content: JSON.stringify({ files:[], references:[{path:'./tsconfig.app.json'},{path:'./tsconfig.node.json'}] },null,2)+'\n' });
  files.push({ path:'tsconfig.app.json', content: JSON.stringify({ compilerOptions:{ target:'ES2022',useDefineForClassFields:true,lib:['ES2022','DOM','DOM.Iterable'],allowJs:false,skipLibCheck:true,esModuleInterop:true,allowSyntheticDefaultImports:true,strict:true,forceConsistentCasingInFileNames:true,module:'ESNext',moduleResolution:'Bundler',resolveJsonModule:true,isolatedModules:true,noEmit:true,jsx:'react-jsx' },include:['src'] },null,2)+'\n' });
  files.push({ path:'tsconfig.node.json', content: JSON.stringify({ compilerOptions:{ composite:true,skipLibCheck:true,module:'ESNext',moduleResolution:'Bundler',allowImportingTsExtensions:true },include:['vite.config.ts'] },null,2)+'\n' });
  files.push({ path:'vite.config.ts', content: generatedViteConfig(input.pages) });
  files.push({ path:'src/main.tsx', content: generatedMain() });
  files.push({ path:'src/App.tsx', content: generatedApp() });
  files.push({ path:'src/site-data.ts', content: `/* Generated by ${GENERATED_BY} */\nexport const site = ${JSON.stringify(input.seo, null, 2)} as const;\nexport const pages = ${JSON.stringify(input.pages, null, 2)} as const;\n` });
  files.push({ path:'src/assets.ts', content: assetImports(input.assets) });
  files.push({ path:'src/styles.css', content: nodeCss(input.pages, input.fonts, input.assets) });
  files.push({ path:'README.md', content: `# ${input.projectName}\n\nGenerated with Nila Website Builder.\n\n## Run\n\n\`\`\`bash\nnpm install\nnpm run dev\n\`\`\`\n\n## Production\n\n\`\`\`bash\nnpm run build\n\`\`\`\n\nThe generated site has no runtime dependency on Nila.\n` });
  files.push({ path:'.gitignore', content:'node_modules\ndist\n.env\n.env.*\n!.env.example\n' });
  files.push({ path:'.nila/project.json', content: JSON.stringify({ generator:GENERATED_BY, generatedAt:new Date().toISOString(), schemaVersion:8, projectName:input.projectName, pages:input.pages, assets:input.assets.map(({dataUrl,...asset})=>asset), fonts:input.fonts, seo:input.seo },null,2)+'\n' });
  for (const seoFile of generateSeoFiles(input.seo, input.pages)) files.push({ path:seoFile.path, content:seoFile.content });
  for (const page of input.pages) files.push({ path:page.isHome?'index.html':`${page.slug}/index.html`, content:htmlForPage(input,page) });
  for (const asset of input.assets) {
    const folder = asset.kind === 'font' ? 'fonts' : 'media';
    const bytes = dataUrlBytes(asset.dataUrl);
    files.push({ path:`src/assets/${folder}/${safeFileName(asset.fileName)}`, content:bytes, binary:true });
    if (asset.kind !== 'font') files.push({ path:`public/assets/media/${safeFileName(asset.fileName)}`, content:bytes, binary:true });
  }
  return files;
}
